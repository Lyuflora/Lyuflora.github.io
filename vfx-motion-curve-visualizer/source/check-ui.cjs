const { chromium } = require(process.argv[2]);
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5174/');
  await page.waitForSelector('.three-host canvas');
  await page.waitForTimeout(1200);
  for (const [width, height] of [[1920,1080],[2560,1440],[1440,900],[1280,800]]) {
    await page.setViewportSize({width,height});
    await page.waitForTimeout(200);
    const dimensions = await page.evaluate(() => ({w:innerWidth,h:innerHeight,sw:document.documentElement.scrollWidth,sh:document.documentElement.scrollHeight}));
    console.log('viewport', dimensions);
    assert(dimensions.sw <= width, 'horizontal overflow');
    assert(dimensions.sh <= height, 'desktop vertical overflow');
  }
  await page.setViewportSize({width:1920,height:1080});
  await page.waitForTimeout(300);
  await page.screenshot({path:'ui-overview.png'});
  await page.getByRole('button',{name:'Focus velocity graph',exact:true}).click();
  await page.waitForTimeout(300);
  await page.screenshot({path:'ui-velocity-focus.png'});
  assert(await page.locator('.layout-velocity').count());
  await page.getByRole('button',{name:'Restore overview from velocity graph',exact:true}).click();
  const timeBefore = await page.getByRole('slider',{name:'Timeline seconds'}).inputValue();
  const keyBefore = await page.getByRole('combobox',{name:'Selected keyframe'}).inputValue();
  await page.getByRole('button',{name:'Focus position graph',exact:true}).click();
  assert.equal(await page.getByRole('slider',{name:'Timeline seconds'}).inputValue(),timeBefore);
  assert.equal(await page.getByRole('combobox',{name:'Selected keyframe'}).inputValue(),keyBefore);
  await page.setViewportSize({width:1280,height:800});
  await page.waitForTimeout(200);
  await page.screenshot({path:'ui-compact-focus.png'});
  await page.getByRole('button',{name:'Restore overview from position graph',exact:true}).click();
  await page.setViewportSize({width:1920,height:1080});
  await page.getByRole('button',{name:'Edit obstacle',exact:true}).click();
  assert.equal(await page.getByRole('tab',{name:'Scene',exact:true}).getAttribute('aria-selected'),'true');
  assert(await page.locator('.studio-inspector .obstacle-inspector').isVisible());
  const pos = page.getByRole('spinbutton',{name:'3D obstacle position x',exact:true});
  await pos.fill('2.5'); await pos.press('Enter');
  assert.equal(await pos.inputValue(),'2.5');
  await page.getByRole('button',{name:'Resize',exact:true}).click();
  const size = page.getByRole('spinbutton',{name:'3D obstacle size x',exact:true});
  await size.fill('1.8'); await size.press('Enter');
  assert.equal(await size.inputValue(),'1.8');
  await page.screenshot({path:'ui-obstacle.png'});
  await page.getByRole('button',{name:'Finish obstacle editing',exact:true}).click();
  await page.getByRole('tab',{name:'Selection',exact:true}).click();
  const velocity = page.getByRole('spinbutton',{name:'Selected key velocity',exact:true});
  await velocity.fill('1.25'); await velocity.press('Enter');
  assert.equal(await velocity.inputValue(),'1.25');
  await page.getByRole('button',{name:'Hide inspector',exact:true}).first().click();
  assert(!await page.getByRole('complementary',{name:'Inspector'}).isVisible());
  await page.getByRole('button',{name:'Show inspector',exact:true}).click();
  assert.equal(await velocity.inputValue(),'1.25');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download',exact:true}).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(),'vfx-motion.json');
  await page.getByRole('button',{name:'Presets',exact:true}).click();
  assert(await page.getByRole('dialog').isVisible());
  await page.keyboard.press('Escape');
  assert(!await page.getByRole('dialog').isVisible());
  await page.getByRole('tab',{name:'Selection',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab',{name:'Scene',exact:true}).getAttribute('aria-selected'),'true');
  await page.setViewportSize({width:800,height:1000});
  await page.waitForTimeout(200);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors,[]);
  console.log('PASS: layouts, obstacle position/size, key edit, inspector, download, presets; no runtime errors.');
  await browser.close();
})().catch(e => {console.error(e);process.exit(1)});
